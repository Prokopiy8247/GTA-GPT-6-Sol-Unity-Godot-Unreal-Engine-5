def profile(coll, label, points, half_width, key):
    verts = [(x, -half_width, z) for x,z in points] + [(x, half_width, z) for x,z in points]
    count = len(points)
    faces = [tuple(range(count-1,-1,-1)), tuple(range(count,2*count))]
    faces += [(i,(i+1)%count,(i+1)%count+count,i+count) for i in range(count)]
    return mesh(coll,label,verts,faces,key)

